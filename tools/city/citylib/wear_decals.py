"""SLICE6 wear decals: one shared, code-made decal sheet and the mesh decals that place it on hero walls.

The slice read "clean cardboard": uniform lime-wash with no staining. Real Cityhub plaster (gf_21, gf_24, h08,
h16) has a dark splash band at the wall foot, grey-green monsoon streaks hanging from cornices and sills, damp
patches round downpipes, lighter repaired-plaster patches and hand/scuff wear at gates. These are mesh decals
(research 2, item 4): small quads 12 mm proud of the wall on ONE material (MAT_WearDecal_A, shader
BatchIsland/World/WearDecal) so a hero pays one extra draw call for all of them.

Sheet (T_WearDecals_A, 1024 px, linear): RGB = albedo multiplier / 2 (0.5 = no change, so one blend state
darkens and lightens: Blend DstColor SrcColor), A = coverage. Cells below in UV space (v up). The `base` and
`drip` rows span the full width and tile along the wall (u = metres / 4). Own work, generated by
tools/textures/build_wear_decals.py from these rules (no photo pixels).

Placement is deterministic (hashes of position), from FacadeLayout.facades (hero_blocks records every storey of
every wall with its openings), so decals never float across a recessed opening.
"""
from __future__ import annotations

import math

from . import hero_geom as G
from . import materials as M

MATERIAL = M.WEAR_DECAL
SHEET_PX = 1024
INSET = 4 / SHEET_PX
PROUD = 0.012          # m in front of the wall plane (shader adds a depth offset)
BASE_TILE_M = (4.0, 1.2)   # metres the base row covers (u along the wall, v up)
DRIP_TILE_M = (4.0, 1.6)

CELLS = {
    "base": (0.0, 0.0, 1.0, 0.125),
    "drip": (0.0, 0.125, 1.0, 0.25),
    "streak0": (0.0, 0.25, 0.25, 0.5), "streak1": (0.25, 0.25, 0.5, 0.5),
    "streak2": (0.5, 0.25, 0.75, 0.5), "streak3": (0.75, 0.25, 1.0, 0.5),
    "damp0": (0.0, 0.5, 0.25, 0.75), "damp1": (0.25, 0.5, 0.5, 0.75),
    "patch0": (0.5, 0.5, 0.75, 0.75), "patch1": (0.75, 0.5, 1.0, 0.75),
    "louvre": (0.0, 0.75, 0.25, 1.0),
    "wear0": (0.25, 0.75, 0.5, 1.0), "wear1": (0.5, 0.75, 0.75, 1.0),
    "pipe": (0.75, 0.75, 1.0, 1.0),
}
FULL_WIDTH = ("base", "drip")


def cell(name: str) -> tuple[float, float, float, float]:
    """Cell rect (u0, v0, u1, v1), inset against mip bleeding (full-width rows keep u 0..1 so they tile)."""
    u0, v0, u1, v1 = CELLS[name]
    if name in FULL_WIDTH:
        return u0, v0 + INSET, u1, v1 - INSET
    return u0 + INSET, v0 + INSET, u1 - INSET, v1 - INSET


def _h(*xs) -> float:
    n = math.sin(sum(x * k for x, k in zip(xs, (12.9898, 78.233, 37.719, 4.581))) + 0.5) * 43758.5453
    return n - math.floor(n)


def _quad(m, e: G.Edge, s0, s1, z0, z1, uv_rect, d=PROUD, u_tile=None):
    """Decal quad on wall edge e; uv_rect = (u0, v0, u1, v1); u_tile = metres per u for tiling rows."""
    u0, v0, u1, v1 = uv_rect
    if u_tile:
        ua, ub = s0 / u_tile, s1 / u_tile
    else:
        ua, ub = u0, u1
    G.quad(m, e.p(s0, d, z0), e.p(s1, d, z0), e.p(s1, d, z1), e.p(s0, d, z1),
           [(ua, v0), (ub, v0), (ub, v1), (ua, v1)], MATERIAL)


def _free(intervals, cuts, lo=0.0, hi=None):
    """Intervals minus cut ranges (s0, s1); pieces shorter than 0.25 m dropped."""
    out = []
    for a, b in intervals:
        pieces = [(a, b)]
        for c0, c1 in cuts:
            nxt = []
            for p0, p1 in pieces:
                if c1 <= p0 or c0 >= p1:
                    nxt.append((p0, p1))
                    continue
                if c0 > p0:
                    nxt.append((p0, c0))
                if c1 < p1:
                    nxt.append((c1, p1))
            pieces = nxt
        out += [(p0, p1) for p0, p1 in pieces if p1 - p0 >= 0.25]
    return out


def _cuts(info, z0, z1, pad=0.03):
    return [(o[0] - pad, o[1] + pad) for _, code, o in info if o[2] < z1 and o[3] > z0]


def place(m, facades, ground_z0: float, pipes=(), density: float = 1.0) -> int:
    """Decal quads into MeshData m for every recorded facade storey. ground_z0 = the ground storey's floor line
    (walls start there, the dark plinth skirting is below). Returns the number of quads."""
    n0 = len(m.faces)
    for a, b, zf0, zf1, st, info in facades:
        e = G.Edge(a, b)
        L = e.length
        if L < 1.0 or getattr(st, "kind", "") == "skip":
            continue
        key = (round(a[0], 1), round(a[1], 1), round(zf0, 1))
        ground = abs(zf0 - ground_z0) < 0.05
        # 1. base grime: wall foot splash band, broken round door openings
        if ground:
            z0, z1 = zf0 - 0.05, zf0 + 1.0
            vb = cell("base")
            v1 = vb[1] + (vb[3] - vb[1]) * (z1 - z0) / BASE_TILE_M[1]
            for s0, s1 in _free([(0.0, L)], _cuts(info, z0, z1)):
                _quad(m, e, s0, s1, z0, z1, (0, vb[1], 1, v1), u_tile=BASE_TILE_M[0])
        # 2. drip band hanging under the storey's top moulding, on about half the wall in 3-9 m runs
        top = zf1 - 0.42
        dz = 0.9 + 0.7 * _h(*key, 1)
        z0 = top - dz
        vd = cell("drip")
        v0 = vd[3] - (vd[3] - vd[1]) * dz / DRIP_TILE_M[1]
        s = 0.3 + 2.0 * _h(*key, 2)
        runs = []
        while s < L - 0.5:
            ln = 3.0 + 6.0 * _h(*key, s, 3)
            if _h(*key, s, 4) < 0.5 * density:
                runs.append((s, min(L - 0.2, s + ln)))
            s += ln + 1.0 + 4.0 * _h(*key, s, 5)
        for s0, s1 in _free(runs, _cuts(info, z0, top)):
            _quad(m, e, s0, s1, z0, top, (0, v0, 1, vd[3]), u_tile=DRIP_TILE_M[0])
        # 3. streaks under raised sills (upper-floor windows)
        for c, code, (o0, o1, oz0, oz1) in info:
            if code not in "FS" or oz0 - zf0 < 0.5 or st.kind != "windows":
                continue
            if _h(c, zf0, *key[:2], 6) > 0.8 * density:
                continue
            z1 = oz0 + 0.02
            z0 = max(zf0 + 0.02, z1 - 1.2)
            w = (o1 - o0) * 0.5 + 0.05
            _quad(m, e, c - w, c + w, z0, z1, cell(f"streak{int(_h(c, zf0, 7) * 4) % 4}"))
        # 4. repaired plaster patches and damp patches on solid wall
        solid = _free([(0.4, L - 0.4)], _cuts(info, zf0, zf1, 0.1))
        for s0, s1 in solid:
            span = s1 - s0
            if span < 1.0:
                continue
            for k in range(int(span / 12.0 * density + _h(s0, zf0, 8))):
                w = 0.7 + 0.9 * _h(s0, k, 9)
                if span < w + 0.2:
                    break
                sc = s0 + 0.1 + (span - w - 0.2) * _h(s0, k, 10)
                hz = 0.6 + 0.6 * _h(s0, k, 11)
                zc = zf0 + 0.6 + (zf1 - zf0 - 1.6) * _h(s0, k, 12)
                _quad(m, e, sc, sc + w, zc, zc + hz, cell(f"patch{int(_h(s0, k, 13) * 2) % 2}"))
            if ground and _h(s0, 14) < 0.45 * density and span > 1.6:
                w = 1.0 + 0.8 * _h(s0, 15)
                sc = s0 + (span - w) * _h(s0, 16)
                _quad(m, e, sc, sc + w, zf0 - 0.05, zf0 + 0.9 + 0.6 * _h(s0, 17), cell(f"damp{int(_h(s0, 18) * 2) % 2}"))
    # 5. downpipe stains: a streak column behind each pipe and a damp patch at its foot
    for (pu, pv), pz0, pz1 in pipes:
        best = None
        for a, b, zf0, zf1, st, info in facades:
            if abs(zf0 - ground_z0) > 0.05:
                continue
            e = G.Edge(a, b)
            dx, dy = pu - a[0], pv - a[1]
            s = dx * e.t[0] + dy * e.t[1]
            d = dx * e.n[0] + dy * e.n[1]
            if -0.05 <= s <= e.length + 0.05 and abs(d) < 0.3 and (best is None or abs(d) < best[2]):
                best = (e, s, abs(d))
        if best is None:
            continue
        e, s, _ = best
        _quad(m, e, s - 0.3, s + 0.3, ground_z0 - 0.05, min(pz1, ground_z0 + 3.2), cell("pipe"))
        _quad(m, e, s - 0.7, s + 0.7, ground_z0 - 0.05, ground_z0 + 1.1, cell("damp0"))
    return len(m.faces) - n0


def wear_quad(m, a, b, z0, z1, name: str, d=PROUD) -> None:
    """One named decal on the wall segment a -> b (building on the left), e.g. gate wear on a pier face."""
    e = G.Edge(a, b)
    _quad(m, e, 0.0, e.length, z0, z1, cell(name), d=d)
